export type SKey = keyof typeof S;

export function tr(lang: Lang, key: SKey, vars?: Record<string, string | number>): string {
  let s: string = S[key][lang] ?? S[key].en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useM() {
  const { lang, reducedMotion } = useSettings();
  return {
    lang,
    reduced: reducedMotion,
    m: (key: SKey, vars?: Record<string, string | number>) => tr(lang, key, vars),
    l: (v: L | undefined | null) => (v ? v[lang] || v.en : ""),
  };
}
